// ---- encoding ----
// Strings are JSON.stringify output with invisible code units also escaped as \uXXXX (lowercase hex),
// so goldens stay readable and editors cannot alter them. The set is part of the format (README).
const INVISIBLE = /[\u007f-\u00a0\u00ad\u1680\u180e\u2000-\u200f\u2028-\u202f\u205f-\u206f\u3000\ufe00-\ufe0f\ufeff\ufff9-\ufffb]/g
const s = (str) => JSON.stringify(str).replace(INVISIBLE, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)
/** Result spelling: JSON for strings/numbers/booleans, markers for the rest. */
function enc(v) {
  if (v === undefined) return '<missing>'
  if (v === null) return '<null>'
  if (Array.isArray(v)) return '<array>'
  if (typeof v === 'object') return '<object>'
  if (typeof v === 'string') return s(v)
  if (typeof v === 'boolean') return String(v)
  if (typeof v === 'number' && Number.isFinite(v)) return String(v) // == JSON.stringify for finite numbers
  throw new Error(`unexpected result ${typeof v} ${String(v)}`)
}
/** Argument spelling (params, defaults): JSON, plus undefined, NaN, ±Infinity and -0 that JSON cannot spell. */
function lit(v) {
  if (v === undefined) return 'undefined'
  if (typeof v === 'number') return Object.is(v, -0) ? '-0' : String(v)
  if (Array.isArray(v)) return `[${v.map(lit).join(',')}]`
  if (v !== null && typeof v === 'object') return `{${Object.keys(v).map((k) => `${s(k)}:${lit(v[k])}`).join(',')}}`
  return s(v)
}
const ctx = (locale, fallback, page) => `${s(locale)}|${s(fallback)}, ${s(page)}`

// ---- golden writer ----
const utf8 = (a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b))
function write(name, title, lines) {
  const byCall = new Map()
  for (const [call, result] of lines) {
    const line = `${call} → ${result}`
    if (byCall.has(call) && byCall.get(call) !== line) throw new Error(`conflicting results for ${call}`)
    byCall.set(call, line)
  }
  const body = [...byCall.values()].sort(utf8)
  const text = [`# compat: ${title}`, '', ...HEADER, '', '```text', ...body, '```', ''].join('\n')
  writeFileSync(`${GOLDEN}/${name}.md`, text)
  console.log(`${name}.md: ${body.length} lines`)
}

// ---- load ----
const errors = []
const { error: origError, warn: origWarn } = console
console.error = console.warn = (msg) => errors.push(String(msg))
const files = listTranslationFiles(LOCALES)
const loaded = loadTranslationDir(LOCALES)
console.error = origError
console.warn = origWarn

const prefix = resolve(LOCALES) + sep
const skipped = new Map()
for (const msg of errors) {
  const m =
    /^\[i18n\] Skipping translation file: (.+): expected a JSON object$/.exec(msg) ??
    /^\[i18n\] Failed to load translation file: (.+)$/.exec(msg)
  if (!m || !m[1].startsWith(prefix)) throw new Error(`unexpected loader message: ${msg}`)
  const rel = m[1].slice(prefix.length).split(sep).join('/')
  skipped.set(rel, msg.includes('expected a JSON object') ? 'skip: not an object' : 'skip: invalid JSON')
}

const loadLines = []
for (const { relativePath } of files) {
  const c = classifyTranslationRelativePath(relativePath)
  const status =
    skipped.get(relativePath) ??
    (c.type === 'root' ? `root ${c.locale}` : c.type === 'page' ? `page ${c.pageName} ${c.locale}` : 'ignore')
  loadLines.push([`file(${s(relativePath)})`, s(status)])
}

class Oracle extends BaseI18n {
  constructor() {
    super({ missingWarn: false, missingHandler: () => {} })
    this.locale = 'en'
    this.fallback = 'en'
    this.route = 'index'
  }
  getLocale() { return this.locale }
  getFallbackLocale() { return this.fallback }
  getRoute() { return this.route }
  at(locale, fallback, page) {
    this.locale = locale
    this.fallback = fallback
    this.route = page
    return this
  }
}
const i18n = new Oracle()
const chunks = []
for (const locale of Object.keys(loaded.root)) chunks.push([locale, 'index', loaded.root[locale]])
for (const page of Object.keys(loaded.routes)) {
  for (const locale of Object.keys(loaded.routes[page])) chunks.push([locale, page, loaded.routes[page][locale]])
}
for (const [locale, page, tree] of chunks) i18n.loadTranslationsCore(locale, tree, false, page)

/** Dotted paths of every raw leaf (primitive, empty object/array), `__proto__` keys skipped. */
function leafPaths(node, path, out) {
  for (const k of Object.keys(node)) {
    if (k === '__proto__') continue
    const p = path === null ? k : `${path}.${k}`
    const v = node[k]
    if (v !== null && typeof v === 'object' && Object.keys(v).length > 0) leafPaths(v, p, out)
    else out.push(p)
  }
  return out
}
for (const [locale, page] of chunks) {
  const tree = i18n.helper.getCache(locale, page)
  for (const p of leafPaths(tree, null, [])) {
    loadLines.push([`load(${s(locale)}, ${s(page)}, ${s(p)})`, enc(getByPath(tree, p))])
  }
}
mkdirSync(GOLDEN, { recursive: true })
write('load', 'load', loadLines)

